#normalised volatility

codon_reshuffle = function(codon_freqs){
  F_total = sum(as.numeric(codon_freqs[1:2]))
  L_total = sum(as.numeric(codon_freqs[3:8]))
  I_total = sum(as.numeric(codon_freqs[9:11]))
  V_total = sum(as.numeric(codon_freqs[12:15]))
  S_total = sum(as.numeric(codon_freqs[16:21]))
  P_total = sum(as.numeric(codon_freqs[22:25]))
  T_total = sum(as.numeric(codon_freqs[26:29]))
  A_total = sum(as.numeric(codon_freqs[30:33]))
  Y_total = sum(as.numeric(codon_freqs[34:35]))
  H_total = sum(as.numeric(codon_freqs[36:37]))
  Q_total = sum(as.numeric(codon_freqs[38:39]))
  N_total = sum(as.numeric(codon_freqs[40:41]))
  K_total = sum(as.numeric(codon_freqs[42:43]))
  D_total = sum(as.numeric(codon_freqs[44:45]))
  E_total = sum(as.numeric(codon_freqs[46:47]))
  C_total = sum(as.numeric(codon_freqs[48:49]))
  R_total = sum(as.numeric(codon_freqs[50:55]))
  G_total = sum(as.numeric(codon_freqs[56:59]))
  
  codon_freqs[1:2] = rep(F_total/2, 2)
  codon_freqs[3:8] = rep(L_total/6, 6)
  codon_freqs[9:11] = rep(I_total/3, 3)
  codon_freqs[12:15] = rep(V_total/4, 4)
  codon_freqs[16:21] = rep(S_total/6, 6)
  codon_freqs[22:25] = rep(P_total/4, 4)
  codon_freqs[26:29] = rep(T_total/4, 4)
  codon_freqs[30:33] = rep(A_total/4, 4)
  codon_freqs[34:35] = rep(Y_total/2, 2)
  codon_freqs[36:37] = rep(H_total/2, 2)
  codon_freqs[38:39] = rep(Q_total/2, 2)
  codon_freqs[40:41] = rep(N_total/2, 2)
  codon_freqs[42:43] = rep(K_total/2, 2)
  codon_freqs[44:45] = rep(D_total/2, 2)
  codon_freqs[46:47] = rep(E_total/2, 2)
  codon_freqs[48:49] = rep(C_total/2, 2)
  codon_freqs[50:55] = rep(R_total/6, 6)
  codon_freqs[56:59] = rep(G_total/4, 4)
  
  return(codon_freqs)
}
